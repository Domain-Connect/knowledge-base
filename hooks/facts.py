"""MkDocs hook: replace {{ facts.<key> }} placeholders with values from data/*.yml.

Ecosystem numbers (templates, service providers, DNS providers, domain share, ...)
change with every statistics export, so pages reference them by key instead of
hard-coding them:

    Domain Connect has {{ facts.templates }} templates.

data/facts.yml is generated by .github/.scripts/update_facts.py. data/sources.yml
is hand-maintained; each entry under its top-level `sources:` key becomes the
placeholders src_<key> (a Markdown link with date and note), src_<key>_url,
src_<key>_title and src_<key>_date. Override
the files in the MkDocs config with:

    extra:
      facts_files: [data/facts.yml, data/sources.yml]

An unknown or duplicate key fails the build.
"""

import pathlib
import re

import yaml
from mkdocs.exceptions import PluginError

DEFAULT_FILES = ["data/facts.yml", "data/sources.yml"]
PLACEHOLDER = re.compile(r"\{\{\s*facts\.([A-Za-z0-9_]+)\s*\}\}")

_facts = {}


def source_facts(key, source):
    title, url = source["title"], source.get("url")
    text = f"[{title}]({url})" if url else title
    details = [str(source[field]) for field in ("date", "note") if source.get(field)]
    if details:
        text += f" ({', '.join(details)})"
    facts = {f"src_{key}": text, f"src_{key}_title": title}
    for field in ("url", "date"):
        if source.get(field):
            facts[f"src_{key}_{field}"] = str(source[field])
    return facts


def on_config(config):
    root = pathlib.Path(config.config_file_path).parent
    _facts.clear()
    for name in config.extra.get("facts_files", DEFAULT_FILES):
        path = root / name
        try:
            with open(path, encoding="utf-8") as f:
                data = yaml.safe_load(f) or {}
        except OSError as exc:
            raise PluginError(f"facts: cannot read {path}: {exc}")
        facts = {key: str(value) for key, value in data.items() if key != "sources"}
        for key, source in (data.get("sources") or {}).items():
            facts.update(source_facts(key, source))
        for key, value in facts.items():
            if key in _facts:
                raise PluginError(f"facts: duplicate key '{key}' in {path}")
            _facts[key] = value
    return config


def on_page_markdown(markdown, page, config, files):
    def replace(match):
        key = match.group(1)
        if key not in _facts:
            raise PluginError(f"facts: unknown key '{key}' in {page.file.src_uri}")
        return _facts[key]

    return PLACEHOLDER.sub(replace, markdown)
